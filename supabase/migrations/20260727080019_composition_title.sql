-- =============================================================================
-- compositions.title — 수록곡 작품 제목 (자유 텍스트)
-- =============================================================================
-- 지금까지 수록곡은 composer + catalog_number 로만 식별돼, 목록·상세에
-- "Beethoven · Op.67"처럼 번호로만 남았다. 사람이 읽는 제목을 담을 칸이 없다.
--
-- work_id(정규 작품 참조)와 공존한다 — 대체가 아니다:
--   · work_id  = Open Opus 등 외부 식별자에 매칭된 정규 작품 (§3-4, 대 2)
--   · title    = 사용자가 음반 표지에서 읽어 적은 자유 텍스트. 매칭 여부와 무관.
-- 매칭이 붙으면 표시에서 Work 정규명을 우선하되 title은 그대로 보존한다
-- (표기 변형·발췌·편곡판 등 음반 고유 정보가 title에만 있는 경우가 많다).
--
-- nullable: 선택 입력이며, 기존 행은 null로 남는다(무방).
-- =============================================================================

alter table public.compositions add column title text;
