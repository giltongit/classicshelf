/// KDC(한국십진분류법) 코드에서 장르(대분류/중분류)를 런타임 파생한다.
///
/// 저장하지 않고 매번 kdc 필드에서 계산한다 — 매핑을 고치면 전체 앱에 즉시 반영되고
/// Drift/Supabase 스키마 변경이 필요 없다 (결정: 장르 정규화 Q1).
///
/// KDC 계층 구조 (한국도서관협회 KDC 6판 기준):
///   1자리 — 주류(main class), 10구분 (0~9)
///   2자리 — 강목(division), 100구분
///   3자리 — 요목(section), 1000구분 (예: 813 = 한국소설)
///   소수점 이하 — 세목(subsection), 예: 813.6 = 한국 현대소설(단편)
///
/// 이 파일은 대분류(1자리) + 중분류(2자리)까지만 다룬다. 요목(3자리) 이하는
/// 더 세분화된 정보이나, 도서관마다 부여 방식이 갈리고 장르 표시 목적엔
/// 과하게 세밀하여 채택하지 않았다 (결정: 장르 정규화 Q3).
library;

/// KDC에서 파생된 장르. [main]은 항상 존재, [sub]는 강목 매핑이 없거나
/// [미사용] 구간이면 null (이 경우 대분류만 표시).
class KdcGenre {
  final String main;
  final String? sub;

  const KdcGenre(this.main, this.sub);

  /// 표시용 라벨. 예: "문학 · 한국문학" 또는 중분류 없으면 "문학"
  String get label => sub == null ? main : '$main · $sub';

  /// 대분류 > 중분류 경로형 라벨. 예: "철학 > 심리학" (중분류 없으면 대분류만)
  String get pathLabel => sub == null ? main : '$main > $sub';

  @override
  String toString() => label;
}

/// 대분류 10구분을 KDC 순서(0~9) 그대로 반환 — "지형도"는 지도이므로 항목
/// 개수·인기순이 아니라 고정된 순서로 배치되어야 매번 같은 위치를 학습할 수 있다
/// (장르 지형도 §10 후속 스펙).
List<MapEntry<String, String>> get kdcMainClassesOrdered =>
    _kdcMainClass.entries.toList();

/// 특정 대분류(1자리, 예: '8') 안의 중분류를 KDC 코드 순서대로 반환.
/// [미사용] 구간은 애초에 _kdcDivision에 없으므로 자동으로 빠진다.
List<MapEntry<String, String>> kdcDivisionsOf(String mainDigit) {
  final entries = _kdcDivision.entries
      .where((e) => e.key.startsWith(mainDigit))
      .toList()
    ..sort((a, b) => a.key.compareTo(b.key));
  return entries;
}

/// kdc 필드 값(예: '813.6', '813', '8')에서 [KdcGenre]를 파생한다.
/// kdc가 null/빈 문자열/숫자로 시작하지 않으면 null 반환.
KdcGenre? kdcToGenre(String? kdc) {
  if (kdc == null) return null;
  final trimmed = kdc.trim();
  if (trimmed.isEmpty) return null;

  final mainKey = trimmed[0];
  final main = _kdcMainClass[mainKey];
  if (main == null) return null;

  if (trimmed.length < 2) return KdcGenre(main, null);

  final divKey = trimmed.substring(0, 2);
  final sub = _kdcDivision[divKey];
  return KdcGenre(main, sub);
}

